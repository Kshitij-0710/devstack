fn makefile(project: &Project) -> String {
    format!(
        r#"up:
	docker compose up --build

down:
	docker compose down

logs:
	docker compose logs -f

rebuild:
	docker compose build --no-cache

app-shell:
	{}

db-shell:
	docker compose exec postgres sh -lc 'psql -U "$$POSTGRES_USER" -d "$$POSTGRES_DB"'
"#,
        project.stack.app_shell()
    )
}

fn compose_file(project: &Project) -> String {
    let app_extra_volume = if project.stack.uses_node_modules_volume() {
        "      - node_modules:/workspace/app/node_modules\n"
    } else {
        ""
    };

    let worker_services = if project.stack.uses_beat() {
        python_worker_services()
    } else {
        node_worker_service()
    };

    let volumes = if project.stack.uses_node_modules_volume() {
        r#"
volumes:
  postgres_data:
  redis_data:
  node_modules:
"#
    } else {
        r#"
volumes:
  postgres_data:
  redis_data:
"#
    };

    format!(
        r#"services:
  app:
    build:
      context: .
      dockerfile: docker/Dockerfile
    command: sh /workspace/docker/start.sh
    env_file:
      - .env
    depends_on:
      postgres:
        condition: service_healthy
      redis:
        condition: service_healthy
    volumes:
      - ./app:/workspace/app
      - ./docker:/workspace/docker
{app_extra_volume}    expose:
      - "{}"

{}  nginx:
    image: nginx:1.27-alpine
    depends_on:
      - app
    ports:
      - "80:80"
    volumes:
      - ./nginx/default.conf:/etc/nginx/conf.d/default.conf:ro

  postgres:
    image: postgres:16-alpine
    env_file:
      - .env
    environment:
      POSTGRES_DB: ${{POSTGRES_DB}}
      POSTGRES_USER: ${{POSTGRES_USER}}
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD}}
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U $${{POSTGRES_USER}} -d $${{POSTGRES_DB}}"]
      interval: 5s
      timeout: 5s
      retries: 20
    ports:
      - "5432:5432"
    volumes:
      - postgres_data:/var/lib/postgresql/data

  redis:
    image: redis:7-alpine
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 5s
      timeout: 3s
      retries: 20
    ports:
      - "6379:6379"
    volumes:
      - redis_data:/data
{}"#,
        project.stack.app_port(),
        worker_services,
        volumes
    )
}

