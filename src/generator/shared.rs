use crate::project::{FileEntry, Project, Stack};

pub fn base_files(project: &Project) -> Vec<FileEntry> {
    vec![
        text_file("README.md", readme(project)),
        text_file(".env", env_file(project)),
        text_file(".env.example", env_file(project)),
        text_file(".gitignore", gitignore(project)),
        text_file(".dockerignore", dockerignore(project)),
        text_file("Makefile", makefile(project)),
        text_file("compose.yaml", compose_file(project)),
        text_file(".github/workflows/ci.yml", ci_workflow(project)),
        text_file("nginx/default.conf", nginx_conf(project)),
    ]
}

pub fn executable_file(path: &'static str, contents: impl Into<String>) -> FileEntry {
    FileEntry {
        path,
        contents: contents.into(),
        executable: true,
    }
}

pub fn text_file(path: &'static str, contents: impl Into<String>) -> FileEntry {
    FileEntry {
        path,
        contents: contents.into(),
        executable: false,
    }
}

pub fn python_dockerfile() -> String {
    r#"FROM python:3.12-slim
WORKDIR /workspace/app
ENV PYTHONDONTWRITEBYTECODE=1
ENV PYTHONUNBUFFERED=1
RUN apt-get update && apt-get install -y build-essential libpq-dev curl && rm -rf /var/lib/apt/lists/*
COPY app/requirements.txt /tmp/requirements.txt
RUN pip install --upgrade pip && pip install -r /tmp/requirements.txt
CMD ["sh", "/workspace/docker/start.sh"]
"#
    .to_string()
}

fn readme(project: &Project) -> String {
    let extra = match project.stack {
        Stack::Node => {
            "The generated app includes Express, BullMQ, Postgres wiring, Redis, an nginx edge, and a worker service."
        }
        Stack::Django => {
            "The generated app includes Django, Postgres, Redis, Celery worker and beat processes, and an nginx edge."
        }
        Stack::Flask => {
            "The generated app includes Flask, Postgres, Redis, Celery worker and beat processes, and an nginx edge."
        }
        Stack::Fastapi => {
            "The generated app includes FastAPI, Postgres, Redis, Celery worker and beat processes, and an nginx edge."
        }
    };

    format!(
        r#"# {}

Generated by DevStack for {}.

{}

## Quickstart

```bash
docker compose up --build
```

The application is available at `http://localhost`.

## Included

- Dockerized app runtime
- Postgres with persistent storage
- Redis for caching and jobs
- Background worker service
- GitHub Actions CI
- `.env` and `.env.example`
- Opinionated project layout for shipping fast

## Handy commands

```bash
make up
make down
make logs
make app-shell
make db-shell
```

## Layout

```text
app/
docker/
nginx/
.github/workflows/
compose.yaml
Makefile
```
"#,
        project.title_name(),
        project.stack.label(),
        extra
    )
}

